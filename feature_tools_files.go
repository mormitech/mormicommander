package main

// The small file utilities of the Files menu over internal/fileutil: create and verify checksum files (cm_CRCCreate,
// cm_CRCCheck, F-332, F-333, F-689, F-690), checksums to the clipboard (F-693), split and combine (cm_FileSplit,
// cm_FileCombine, F-328, F-329, F-687, F-688) and encode/decode (cm_UUEncode, cm_UUDecode, F-330, F-331, F-692).
//
// The engines never replace an existing file unless asked; when one is in the way the result says so in Exists and
// the page asks "Overwrite?" and calls again with Overwrite set.

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"mormicommander/internal/dirsize"
	"mormicommander/internal/fileutil"
)

// toolsFileProgress turns engine progress into a progress event.
func toolsFileProgress(p fileutil.Progress) map[string]any {
	return map[string]any{"current": p.File, "fileDone": p.FileDone, "fileTotal": p.FileTotal, "bytesDone": p.Done, "bytes": p.Total}
}

// toolsAlgorithms parses algorithm names ("MD5", "SHA256"…).
func toolsAlgorithms(names []string) ([]fileutil.Algorithm, error) {
	var out []fileutil.Algorithm
	for _, n := range names {
		a, err := fileutil.ParseAlgorithm(n)
		if err != nil {
			return nil, fmt.Errorf("%s is not a checksum method this app knows.", n)
		}
		out = append(out, a)
	}
	if len(out) == 0 {
		return nil, errors.New("Choose a checksum method.")
	}
	return out, nil
}

// toolsExists tells whether an engine error means "a file is in the way", and which.
func toolsExists(err error) (string, bool) {
	if !errors.Is(err, fs.ErrExist) {
		return "", false
	}
	var pe *fs.PathError
	if errors.As(err, &pe) {
		return pe.Path, true
	}
	return "", true
}

// ToolsAlgorithm is one checksum method for the dialogs.
type ToolsAlgorithm struct {
	Name string `json:"name"`
	Ext  string `json:"ext"`
}

// ChecksumAlgorithms lists the checksum methods in dialog order with their file extensions.
func (t *Tools) ChecksumAlgorithms() []ToolsAlgorithm {
	out := []ToolsAlgorithm{}
	for _, a := range fileutil.Algorithms {
		out = append(out, ToolsAlgorithm{Name: a.String(), Ext: a.Extension()})
	}
	return out
}

// ChecksumFiles keeps the paths that are checksum files (.md5, .sfv, .sha…), for "Verify checksums".
func (t *Tools) ChecksumFiles(paths []string) []string {
	out := []string{}
	for _, p := range paths {
		if fileutil.IsChecksumFile(p) {
			out = append(out, p)
		}
	}
	return out
}

// ToolsCRCCreate asks for checksum files.
type ToolsCRCCreate struct {
	BaseDir    string   `json:"baseDir"`
	Paths      []string `json:"paths"`
	Algorithm  string   `json:"algorithm"`
	OnePerFile bool     `json:"onePerFile"`
	Output     string   `json:"output"` // the common checksum file (full path); "" = TC's default name in BaseDir
	Unix       bool     `json:"unix"`   // LF and "/" (TC's "Unix format"); false = the system's own format
	Overwrite  bool     `json:"overwrite"`
}

// ToolsCRCResult is what creating checksum files did.
type ToolsCRCResult struct {
	Written []string       `json:"written"`
	Hashed  int            `json:"hashed"`
	Bytes   int64          `json:"bytes"`
	Failed  []ToolsFailure `json:"failed"`
	Exists  string         `json:"exists"` // a checksum file is in the way (nothing was written)
}

// CreateChecksums writes checksum files for the selection (folders recursively), in md5sum / shasum / SFV format.
func (t *Tools) CreateChecksums(id string, r ToolsCRCCreate) (ToolsCRCResult, error) {
	if err := t.toolsLocal(r.Paths...); err != nil {
		return ToolsCRCResult{}, err
	}
	if err := t.toolsLocalDir(r.BaseDir); err != nil {
		return ToolsCRCResult{}, err
	}
	algs, err := toolsAlgorithms([]string{r.Algorithm})
	if err != nil {
		return ToolsCRCResult{}, err
	}
	opts := fileutil.CreateOptions{Algorithms: algs, BaseDir: r.BaseDir, Paths: r.Paths, OnePerFile: r.OnePerFile,
		Overwrite: r.Overwrite, Comment: "Generated by mormiCommander"}
	if r.Unix {
		opts.Format = fileutil.FormatUnix
	}
	if !r.OnePerFile && strings.TrimSpace(r.Output) != "" {
		out := strings.TrimSpace(r.Output)
		if !filepath.IsAbs(out) {
			out = filepath.Join(r.BaseDir, out)
		}
		opts.OutputDir = filepath.Dir(out)
		name := filepath.Base(out)
		if ext := algs[0].Extension(); strings.EqualFold(filepath.Ext(name), ext) {
			name = name[:len(name)-len(ext)]
		}
		opts.OutputName = name
		if err := t.toolsLocalDir(opts.OutputDir); err != nil {
			return ToolsCRCResult{}, err
		}
	}
	ctx, end := t.toolsBegin(id)
	defer end()
	progress := t.toolsProgress(id)
	opts.Progress = func(p fileutil.Progress) { progress(toolsFileProgress(p)) }
	res, err := fileutil.CreateChecksums(ctx, opts)
	if p, ok := toolsExists(err); ok {
		return ToolsCRCResult{Exists: p}, nil
	}
	if err != nil {
		return ToolsCRCResult{}, toolsErr(err)
	}
	out := ToolsCRCResult{Written: res.Written, Hashed: res.Hashed, Bytes: res.Bytes, Failed: []ToolsFailure{}}
	for _, f := range res.Failed {
		out.Failed = append(out.Failed, ToolsFailure{Path: f.Path, Error: toolsErrText(f.Err)})
	}
	return out, nil
}

// ToolsVerifyEntry is one line of a checksum file after checking.
type ToolsVerifyEntry struct {
	Name   string `json:"name"`
	Path   string `json:"path"`
	Status string `json:"status"` // "OK", "FAILED", "MISSING", "ERROR"
	Method string `json:"method"`
	Error  string `json:"error"`
}

// ToolsVerifyReport is the result for one checksum file.
type ToolsVerifyReport struct {
	File     string             `json:"file"`
	Entries  []ToolsVerifyEntry `json:"entries"`
	BadLines []string           `json:"badLines"`
	OK       int                `json:"ok"`
	Failed   int                `json:"failed"`
	Missing  int                `json:"missing"`
	Errors   int                `json:"errors"`
	Summary  string             `json:"summary"`
	Text     string             `json:"text"`
}

var toolsStatusWords = map[fileutil.VerifyStatus]string{
	fileutil.StatusOK: "OK", fileutil.StatusFailed: "FAILED", fileutil.StatusMissing: "MISSING", fileutil.StatusError: "ERROR",
}

// VerifyChecksums checks every file listed in the given checksum files (GNU, BSD and SFV formats).
func (t *Tools) VerifyChecksums(id string, paths []string) ([]ToolsVerifyReport, error) {
	files := t.ChecksumFiles(paths)
	if len(files) == 0 {
		return nil, errors.New("Select a checksum file first (.md5, .sfv, .sha, .sha256, .sha512, .blake3…).")
	}
	if err := t.toolsLocal(files...); err != nil {
		return nil, err
	}
	ctx, end := t.toolsBegin(id)
	defer end()
	progress := t.toolsProgress(id)
	reps, err := fileutil.VerifyChecksumFiles(ctx, files, fileutil.VerifyOptions{Progress: func(p fileutil.Progress) { progress(toolsFileProgress(p)) }})
	if err != nil && ctx.Err() != nil {
		return nil, toolsErr(ctx.Err())
	}
	if err != nil && len(reps) == 0 {
		return nil, toolsErr(err)
	}
	out := []ToolsVerifyReport{}
	for _, r := range reps {
		if r == nil {
			continue
		}
		rep := ToolsVerifyReport{File: r.ChecksumFile, OK: r.OK, Failed: r.Failed, Missing: r.Missing, Errors: r.Errors,
			Summary: r.Summary(), Text: r.Text(), Entries: []ToolsVerifyEntry{}, BadLines: []string{}}
		for _, e := range r.Entries {
			ve := ToolsVerifyEntry{Name: e.Name, Path: e.Path, Status: toolsStatusWords[e.Status]}
			if e.Used.Valid() {
				ve.Method = e.Used.String()
			}
			if e.Err != nil {
				ve.Error = toolsErrText(e.Err)
			}
			rep.Entries = append(rep.Entries, ve)
		}
		for _, b := range r.BadLines {
			rep.BadLines = append(rep.BadLines, fmt.Sprintf("Line %d: %s", b.Line, b.Text))
		}
		out = append(out, rep)
	}
	if err != nil && len(out) == 0 {
		return nil, toolsErr(err)
	}
	return out, nil
}

// ChecksumText calculates one checksum per file and returns md5sum-style lines (a single digest for one file), for
// the clipboard.
func (t *Tools) ChecksumText(id string, paths []string, algorithm string, uppercase bool) (string, error) {
	if err := t.toolsLocal(paths...); err != nil {
		return "", err
	}
	algs, err := toolsAlgorithms([]string{algorithm})
	if err != nil {
		return "", err
	}
	ctx, end := t.toolsBegin(id)
	defer end()
	progress := t.toolsProgress(id)
	res, err := fileutil.HashFiles(ctx, paths, algs[0], func(p fileutil.Progress) { progress(toolsFileProgress(p)) })
	if err != nil {
		return "", toolsErr(err)
	}
	for _, r := range res {
		if r.Err != nil {
			return "", fmt.Errorf("%s could not be read: %s", filepath.Base(r.Path), toolsErrText(r.Err))
		}
	}
	return fileutil.ClipboardText(res, algs[0], uppercase), nil
}

// ToolsPreset is one entry of the part size list.
type ToolsPreset struct {
	Name string `json:"name"`
	Size int64  `json:"size"` // -1 = automatic
}

// SplitPresets lists the part sizes of the split dialog.
func (t *Tools) SplitPresets() []ToolsPreset {
	out := []ToolsPreset{}
	for _, p := range fileutil.SizePresets {
		out = append(out, ToolsPreset{Name: p.Name, Size: p.Size})
	}
	return out
}

// ParseSize reads a part size as typed ("700M", "1.44 MB", "4 GB FAT32", "Automatic", a byte count).
func (t *Tools) ParseSize(s string) (int64, error) {
	n, err := fileutil.ParseSize(s)
	if err != nil || n == 0 {
		return 0, errors.New("The part size is not valid. Type a number of bytes, or a size like 700M or 4.7G.")
	}
	return n, nil
}

// ToolsSplit asks for a split.
type ToolsSplit struct {
	Source    string `json:"source"`
	TargetDir string `json:"targetDir"`
	Size      string `json:"size"`
	NoCRC     bool   `json:"noCRC"`
	Overwrite bool   `json:"overwrite"`
}

// ToolsSplitResult is what a split wrote.
type ToolsSplitResult struct {
	Parts   []string `json:"parts"`
	CRCFile string   `json:"crcFile"`
	Exists  string   `json:"exists"`
}

// Split cuts a file into name.001, name.002, … and writes name.crc with the name, size and CRC32 of the whole file.
func (t *Tools) Split(id string, r ToolsSplit) (ToolsSplitResult, error) {
	if err := t.toolsLocal(r.Source); err != nil {
		return ToolsSplitResult{}, err
	}
	if fi, err := os.Stat(r.Source); err != nil || fi.IsDir() {
		return ToolsSplitResult{}, errors.New("Please select a single file to split.")
	}
	if err := t.toolsLocalDir(r.TargetDir); err != nil {
		return ToolsSplitResult{}, err
	}
	size, err := t.ParseSize(r.Size)
	if err != nil {
		return ToolsSplitResult{}, err
	}
	ctx, end := t.toolsBegin(id)
	defer end()
	progress := t.toolsProgress(id)
	opts := fileutil.SplitOptions{Source: r.Source, TargetDir: r.TargetDir, PartSize: size, NoCRCFile: r.NoCRC, Overwrite: r.Overwrite,
		Progress: func(p fileutil.Progress) { progress(toolsFileProgress(p)) },
		FreeSpace: func(dir string) (int64, error) {
			v, err := dirsize.VolumeOf(dir)
			return int64(v.Available), err
		}}
	res, err := fileutil.SplitFile(ctx, opts)
	if p, ok := toolsExists(err); ok {
		return ToolsSplitResult{Exists: p}, nil
	}
	if err != nil {
		return ToolsSplitResult{}, toolsErr(err)
	}
	return ToolsSplitResult{Parts: res.Parts, CRCFile: res.CRCFile}, nil
}

// ToolsCombineInfo is what the combine dialog starts from.
type ToolsCombineInfo struct {
	Parts []string `json:"parts"`
	Name  string   `json:"name"` // the name of the combined file (from the .crc file when there is one)
	CRC   string   `json:"crc"`  // the .crc file that will be checked ("" for none)
	Size  int64    `json:"size"`
	Auto  bool     `json:"auto"` // the parts were found by counting up from one part
}

var toolsPartRE = regexp.MustCompile(`\.(\d{3,})$`)

// CombineInfo finds the parts for the selection: from one part (or the .crc file) every consecutive part; several
// selected numbered parts in number order; other files in the order given (a plain join).
func (t *Tools) CombineInfo(paths []string) (ToolsCombineInfo, error) {
	if err := t.toolsLocal(paths...); err != nil {
		return ToolsCombineInfo{}, err
	}
	var info ToolsCombineInfo
	if len(paths) == 1 {
		parts, err := fileutil.FindParts(paths[0])
		if err != nil {
			return info, errors.New("Select the first part (such as name.001) or the parts to combine.")
		}
		info.Parts, info.Auto = parts, true
	} else {
		info.Parts = append([]string(nil), paths...)
		all := true
		for _, p := range paths {
			if !toolsPartRE.MatchString(p) {
				all = false
			}
		}
		if all {
			sort.SliceStable(info.Parts, func(i, j int) bool {
				a, _ := strconv.Atoi(toolsPartRE.FindStringSubmatch(info.Parts[i])[1])
				b, _ := strconv.Atoi(toolsPartRE.FindStringSubmatch(info.Parts[j])[1])
				return a < b
			})
		}
	}
	first := info.Parts[0]
	prefix := first
	if m := toolsPartRE.FindStringIndex(first); m != nil {
		prefix = first[:m[0]]
		info.Name = filepath.Base(prefix)
	} else {
		info.Name = filepath.Base(first) + ".combined"
	}
	if strings.EqualFold(filepath.Ext(paths[0]), ".crc") {
		prefix = strings.TrimSuffix(paths[0], filepath.Ext(paths[0]))
	}
	if ci, err := fileutil.ReadCRCInfo(prefix + ".crc"); err == nil {
		info.CRC = prefix + ".crc"
		info.Size = ci.Size
		if ci.FileName != "" && !strings.ContainsAny(ci.FileName, `/\`) {
			info.Name = ci.FileName
		}
	}
	return info, nil
}

// ToolsCombine asks for a combine.
type ToolsCombine struct {
	Parts     []string `json:"parts"`
	Auto      bool     `json:"auto"`   // find the parts by counting up from Parts[0]
	Target    string   `json:"target"` // full path of the combined file
	Overwrite bool     `json:"overwrite"`
}

// ToolsCombineResult is what a combine did.
type ToolsCombineResult struct {
	Target  string `json:"target"`
	Parts   int    `json:"parts"`
	Size    int64  `json:"size"`
	Checked bool   `json:"checked"` // size and CRC32 matched the .crc file
	Exists  string `json:"exists"`
}

// Combine joins the parts into one file and, when a .crc file is there, checks the size and CRC32.
func (t *Tools) Combine(id string, r ToolsCombine) (ToolsCombineResult, error) {
	if len(r.Parts) == 0 {
		return ToolsCombineResult{}, errors.New("Nothing is selected.")
	}
	if err := t.toolsLocal(r.Parts...); err != nil {
		return ToolsCombineResult{}, err
	}
	target := strings.TrimSpace(r.Target)
	if target == "" || strings.HasSuffix(target, "/") || strings.HasSuffix(target, `\`) {
		return ToolsCombineResult{}, errors.New("Type the name of the combined file.")
	}
	if err := t.toolsLocalDir(filepath.Dir(target)); err != nil {
		return ToolsCombineResult{}, err
	}
	ctx, end := t.toolsBegin(id)
	defer end()
	progress := t.toolsProgress(id)
	opts := fileutil.CombineOptions{TargetDir: filepath.Dir(target), TargetName: filepath.Base(target), Overwrite: r.Overwrite,
		Progress: func(p fileutil.Progress) { progress(toolsFileProgress(p)) }}
	if r.Auto {
		opts.FirstPart = r.Parts[0]
	} else {
		opts.Parts = r.Parts
	}
	res, err := fileutil.CombineFiles(ctx, opts)
	if p, ok := toolsExists(err); ok {
		return ToolsCombineResult{Exists: p}, nil
	}
	if errors.Is(err, fileutil.ErrCombineMismatch) {
		return ToolsCombineResult{}, fmt.Errorf("The combined file does not match the size and checksum in the .crc file: a part is damaged or missing. The file %s was kept so you can look at it.", target)
	}
	if err != nil {
		return ToolsCombineResult{}, toolsErr(err)
	}
	return ToolsCombineResult{Target: res.Target, Parts: len(res.Parts), Size: res.Size, Checked: res.Checked}, nil
}

// ToolsEncode asks to encode files.
type ToolsEncode struct {
	Sources      []string `json:"sources"`
	Encoding     string   `json:"encoding"` // "mime", "uue", "xxe", "binhex", "base64"
	TargetDir    string   `json:"targetDir"`
	LinesPerPart int      `json:"linesPerPart"`
	Overwrite    bool     `json:"overwrite"`
}

// ToolsFilesResult lists the files a tool wrote.
type ToolsFilesResult struct {
	Files    []string `json:"files"`
	Warnings []string `json:"warnings"`
	Exists   string   `json:"exists"`
}

var toolsEncodings = map[string]fileutil.Encoding{
	"mime": fileutil.EncodingMIME, "uue": fileutil.EncodingUUE, "xxe": fileutil.EncodingXXE, "binhex": fileutil.EncodingBinHex,
	"base64": fileutil.EncodingBase64,
}

// Encode encodes each file as text (MIME base64, UUE, XXE, BinHex); UUE and XXE can be split into parts of N lines.
func (t *Tools) Encode(id string, r ToolsEncode) (ToolsFilesResult, error) {
	if err := t.toolsLocal(r.Sources...); err != nil {
		return ToolsFilesResult{}, err
	}
	if err := t.toolsLocalDir(r.TargetDir); err != nil {
		return ToolsFilesResult{}, err
	}
	enc, ok := toolsEncodings[r.Encoding]
	if !ok {
		return ToolsFilesResult{}, errors.New("Choose an encoding.")
	}
	ctx, end := t.toolsBegin(id)
	defer end()
	progress := t.toolsProgress(id)
	out := ToolsFilesResult{Files: []string{}, Warnings: []string{}}
	for _, src := range r.Sources {
		if fi, err := os.Stat(src); err != nil || fi.IsDir() {
			out.Warnings = append(out.Warnings, filepath.Base(src)+" is a folder; only files can be encoded.")
			continue
		}
		res, err := fileutil.EncodeFile(ctx, fileutil.EncodeOptions{Source: src, Encoding: enc, TargetDir: r.TargetDir,
			LinesPerPart: r.LinesPerPart, Overwrite: r.Overwrite, Progress: func(p fileutil.Progress) { progress(toolsFileProgress(p)) }})
		if p, ok := toolsExists(err); ok {
			out.Exists = p
			return out, nil
		}
		if err != nil {
			return out, toolsErr(err)
		}
		out.Files = append(out.Files, res.Files...)
	}
	return out, nil
}

// ToolsDecode asks to decode files.
type ToolsDecode struct {
	Sources   []string `json:"sources"`
	TargetDir string   `json:"targetDir"`
	Overwrite bool     `json:"overwrite"`
}

// Decode finds encoded data in the files (MIME attachments, UUE, XXE, BinHex, base64; several files are read as one
// stream) and writes the decoded files.
func (t *Tools) Decode(id string, r ToolsDecode) (ToolsFilesResult, error) {
	if err := t.toolsLocal(r.Sources...); err != nil {
		return ToolsFilesResult{}, err
	}
	if err := t.toolsLocalDir(r.TargetDir); err != nil {
		return ToolsFilesResult{}, err
	}
	ctx, end := t.toolsBegin(id)
	defer end()
	progress := t.toolsProgress(id)
	res, err := fileutil.DecodeFiles(ctx, fileutil.DecodeOptions{Sources: r.Sources, TargetDir: r.TargetDir, Overwrite: r.Overwrite,
		Progress: func(p fileutil.Progress) { progress(toolsFileProgress(p)) }})
	if p, ok := toolsExists(err); ok {
		return ToolsFilesResult{Exists: p}, nil
	}
	if errors.Is(err, fileutil.ErrNothingToDecode) {
		return ToolsFilesResult{}, errors.New("No encoded data (MIME, UUE, XXE, BinHex or base64) was found in the selected files.")
	}
	if err != nil {
		return ToolsFilesResult{}, toolsErr(err)
	}
	out := ToolsFilesResult{Files: []string{}, Warnings: append([]string{}, res.Warnings...)}
	for _, f := range res.Files {
		out.Files = append(out.Files, f.Path)
	}
	return out, nil
}
