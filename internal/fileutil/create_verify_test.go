func TestCreateUnreadableFileIsReported(t *testing.T) {
	if runtime.GOOS == "windows" || os.Getuid() == 0 {
		t.Skip("needs Unix permissions and a non-root user")
	}
	dir := makeTree(t, map[string]string{"a.txt": "abc", "locked.txt": "x"})
	os.Chmod(filepath.Join(dir, "locked.txt"), 0)
	defer os.Chmod(filepath.Join(dir, "locked.txt"), 0o644)
	res, err := CreateChecksums(context.Background(), CreateOptions{
		Algorithms: []Algorithm{MD5}, BaseDir: dir, Paths: []string{"a.txt", "locked.txt"}, OutputName: "x", Format: FormatUnix,
	})
	if err != nil {
		t.Fatal(err)
	}
	if res.Hashed != 1 || len(res.Failed) != 1 || !strings.HasSuffix(res.Failed[0].Path, "locked.txt") {
		t.Errorf("result = %+v", res)
	}
	if got := readFile(t, filepath.Join(dir, "x.md5")); got != md5abc+" *a.txt\n" {
		t.Errorf("x.md5 = %q", got)
	}
}

func TestVerifyStatuses(t *testing.T) {
	dir := makeTree(t, map[string]string{"ok.txt": "abc", "bad.txt": "abd", "sub/win.txt": "abc"})
	list := md5abc + " *ok.txt\n" +
		md5abc + " *bad.txt\n" +
		md5abc + " *gone.txt\n" +
		md5abc + " *sub\\win.txt\n" +
		"not a checksum line\n"
	cf := filepath.Join(dir, "list.md5")
	os.WriteFile(cf, []byte(list), 0o644)
	rep, err := VerifyChecksumFile(context.Background(), cf, VerifyOptions{})
	if err != nil {
		t.Fatal(err)
	}
	want := []VerifyStatus{StatusOK, StatusFailed, StatusMissing, StatusOK}
	if len(rep.Entries) != len(want) {
		t.Fatalf("entries = %+v", rep.Entries)
	}
	for i, w := range want {
		if rep.Entries[i].Status != w {
			t.Errorf("entry %d (%s) = %v, want %v", i, rep.Entries[i].Name, rep.Entries[i].Status, w)
		}
	}
	if rep.Entries[1].Actual == "" || rep.Entries[1].Actual == md5abc {
		t.Errorf("failed entry should carry the actual digest, got %q", rep.Entries[1].Actual)
	}
	if rep.AllOK() || rep.Summary() != "2 OK, 1 FAILED, 1 missing, 1 unrecognised line" {
		t.Errorf("summary = %q", rep.Summary())
	}
	txt := rep.Text()
	for _, s := range []string{"FAILED     bad.txt", "missing    gone.txt", "line 5: not a checksum line", "Result: 2 OK"} {
		if !strings.Contains(txt, s) {
			t.Errorf("report text lacks %q:\n%s", s, txt)
		}
	}
}

func TestVerifyForeignFiles(t *testing.T) {
	dir := makeTree(t, map[string]string{"a.txt": "abc", "image.iso": "abc"})
	tests := []struct {
		file, content string
		used          Algorithm
	}{
		// shasum -a 256 (text mode, two spaces)
		{"SHA256SUMS", sha256abc + "  a.txt\n", SHA256},
		// macOS md5 / shasum --tag
		{"tagged.txt", "MD5 (a.txt) = " + md5abc + "\nSHA1 (a.txt) = " + sha1ab + "\n", MD5},
		// b3sum output in a file without telling extension: found by trying
		{"b3.txt", "6437b3ac38465133ffb63b75273a8db548c558465d79db03fd359c6cd5bd9d85  a.txt\n", BLAKE3},
		// download-site style "digest only" file
		{"image.iso.sha256", sha256abc + "\n", SHA256},
		// TC on Windows: CRLF, uppercase
		{"tc.md5", strings.ToUpper(md5abc) + " *a.txt\r\n", MD5},
	}
	for _, tt := range tests {
		p := filepath.Join(dir, tt.file)
		os.WriteFile(p, []byte(tt.content), 0o644)
		rep, err := VerifyChecksumFile(context.Background(), p, VerifyOptions{})
		if err != nil {
			t.Fatalf("%s: %v", tt.file, err)
		}
		if !rep.AllOK() || rep.Entries[0].Used != tt.used {
			t.Errorf("%s: %s, used %v\n%s", tt.file, rep.Summary(), rep.Entries[0].Used, rep.Text())
		}
	}
}

func TestVerifyBaseDirAndMultipleFiles(t *testing.T) {
	dir := makeTree(t, map[string]string{"data/a.txt": "abc", "sums/x.md5": md5abc + " *a.txt\n", "sums/y.sfv": "a.txt 352441C2\n"})
	var last Progress
	reps, err := VerifyChecksumFiles(context.Background(),
		[]string{filepath.Join(dir, "sums/x.md5"), filepath.Join(dir, "sums/y.sfv")},
		VerifyOptions{BaseDir: filepath.Join(dir, "data"), Progress: func(p Progress) { last = p }})
	if err != nil {
		t.Fatal(err)
	}
	if len(reps) != 2 || !reps[0].AllOK() || !reps[1].AllOK() {
		t.Errorf("reports: %s / %s", reps[0].Summary(), reps[1].Summary())
	}
	if last.Total != 6 || last.Done != 6 {
		t.Errorf("progress = %+v", last)
	}
	if _, err := VerifyChecksumFile(context.Background(), filepath.Join(dir, "nope.md5"), VerifyOptions{}); err == nil {
		t.Error("missing checksum file should fail")
	}
	empty := filepath.Join(dir, "empty.md5")
	os.WriteFile(empty, nil, 0o644)
	rep, err := VerifyChecksumFile(context.Background(), empty, VerifyOptions{})
	if err != nil || rep.AllOK() || rep.Summary() != "no files listed" {
		t.Errorf("empty file: %v %q", err, rep.Summary())
	}
}

func TestCancel(t *testing.T) {
	dir := makeTree(t, map[string]string{"a.txt": strings.Repeat("x", 3<<20), "b.txt": "abc"})
	ctx, cancel := context.WithCancel(context.Background())
	_, err := CreateChecksums(ctx, CreateOptions{
		Algorithms: []Algorithm{SHA256}, BaseDir: dir, Paths: []string{"a.txt", "b.txt"}, OutputName: "c",
		Progress: func(Progress) { cancel() },
	})
	if !errors.Is(err, ErrCanceled) {
		t.Fatalf("err = %v, want canceled", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "c.sha256")); !os.IsNotExist(err) {
		t.Error("a cancelled run must not leave a checksum file")
	}
	os.WriteFile(filepath.Join(dir, "l.md5"), []byte(md5abc+" *a.txt\n"), 0o644)
	ctx2, cancel2 := context.WithCancel(context.Background())
	cancel2()
	if _, err := VerifyChecksumFile(ctx2, filepath.Join(dir, "l.md5"), VerifyOptions{}); !errors.Is(err, ErrCanceled) {
		t.Errorf("verify err = %v", err)
	}
}

func TestHashFilesClipboardAndMatch(t *testing.T) {
	dir := makeTree(t, map[string]string{"a.txt": "abc", "b.txt": "abc"})
	a, b := filepath.Join(dir, "a.txt"), filepath.Join(dir, "b.txt")
	res, err := HashFiles(context.Background(), []string{a, b, filepath.Join(dir, "missing")}, MD5, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(res) != 3 || res[0].Digest != md5abc || res[2].Err == nil {
		t.Fatalf("results = %+v", res)
	}
	if got := ClipboardText(res[:1], MD5, true); got != strings.ToUpper(md5abc) {
		t.Errorf("single clipboard = %q", got)
	}
	named := []FileDigest{{Path: "a.txt", Digest: md5abc}, {Path: "b.txt", Digest: md5abc}, {Path: "x", Err: os.ErrNotExist}}
	nl := newlineFor(defaultUnixFormat)
	if got := ClipboardText(named, MD5, false); got != md5abc+" *a.txt"+nl+md5abc+" *b.txt"+nl {
		t.Errorf("multi clipboard = %q", got)
	}
	if got := ClipboardText([]FileDigest{{Path: "a", Digest: "352441c2"}, {Path: "b", Digest: "352441c2"}}, CRC32, false); got != "a 352441C2"+nl+"b 352441C2"+nl {
		t.Errorf("crc clipboard = %q", got)
	}

	tests := []struct {
		digest string
		alg    Algorithm
		ok     bool
		err    bool
	}{
		{md5abc, MD5, true, false},
		{" " + strings.ToUpper(sha256abc) + "\n", SHA256, true, false},
		{"6437b3ac38465133ffb63b75273a8db548c558465d79db03fd359c6cd5bd9d85", BLAKE3, true, false},
		{"352441c2", CRC32, true, false},
		{strings.Repeat("0", 32), MD5, false, false},
		{"xyz", InvalidAlgorithm, false, true},
		{"abcd", InvalidAlgorithm, false, true},
	}
	for _, tt := range tests {
		alg, ok, err := MatchChecksum(context.Background(), a, tt.digest, nil)
		if alg != tt.alg || ok != tt.ok || (err != nil) != tt.err {
			t.Errorf("MatchChecksum(%q) = %v %v %v", tt.digest, alg, ok, err)
		}
	}
}
