// makeTree writes the given files (slash-separated relative paths) under a
// fresh temp folder and returns it.
func makeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, content := range files {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func readFile(t *testing.T, p string) string {
	t.Helper()
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestCreateCommonFile(t *testing.T) {
	dir := makeTree(t, map[string]string{"a.txt": "abc", "b.txt": "", "sub/c.txt": "abc"})
	res, err := CreateChecksums(context.Background(), CreateOptions{
		Algorithms: []Algorithm{MD5},
		BaseDir:    dir,
		Paths:      []string{"a.txt", "b.txt", "sub"},
		OutputName: "all",
		Format:     FormatUnix,
	})
	if err != nil {
		t.Fatal(err)
	}
	want := md5abc + " *a.txt\n" +
		"d41d8cd98f00b204e9800998ecf8427e *b.txt\n" +
		md5abc + " *sub/c.txt\n"
	out := filepath.Join(dir, "all.md5")
	if got := readFile(t, out); got != want {
		t.Errorf("all.md5 =\n%s\nwant\n%s", got, want)
	}
	if res.Hashed != 3 || res.Bytes != 6 || len(res.Written) != 1 || res.Written[0] != out {
		t.Errorf("result = %+v", res)
	}
	rep, err := VerifyChecksumFile(context.Background(), out, VerifyOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if !rep.AllOK() || rep.OK != 3 || rep.Summary() != "3 OK" {
		t.Errorf("verify: %s\n%s", rep.Summary(), rep.Text())
	}
}

func TestCreateFormats(t *testing.T) {
	tests := []struct {
		name string
		opts CreateOptions
		file string
		want string
	}{
		{"sfv unix with comment", CreateOptions{Algorithms: []Algorithm{CRC32}, Format: FormatUnix, Comment: "Generated by mormiCommander"},
			"sub.sfv", "; Generated by mormiCommander\nsub/a.txt 352441C2\nsub/deep/b.txt 352441C2\n"},
		{"sha1 windows", CreateOptions{Algorithms: []Algorithm{SHA1}, Format: FormatWindows},
			"sub.sha", sha1ab + " *sub\\a.txt\r\n" + sha1ab + " *sub\\deep\\b.txt\r\n"},
		{"bsd uppercase", CreateOptions{Algorithms: []Algorithm{MD5}, Format: FormatUnix, BSDStyle: true, Uppercase: true},
			"sub.md5", "MD5 (sub/a.txt) = " + strings.ToUpper(md5abc) + "\nMD5 (sub/deep/b.txt) = " + strings.ToUpper(md5abc) + "\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := makeTree(t, map[string]string{"sub/a.txt": "abc", "sub/deep/b.txt": "abc"})
			tt.opts.BaseDir = dir
			tt.opts.Paths = []string{filepath.Join(dir, "sub")} // absolute path works too
			if _, err := CreateChecksums(context.Background(), tt.opts); err != nil {
				t.Fatal(err)
			}
			if got := readFile(t, filepath.Join(dir, tt.file)); got != tt.want {
				t.Errorf("got %q\nwant %q", got, tt.want)
			}
			rep, err := VerifyChecksumFile(context.Background(), filepath.Join(dir, tt.file), VerifyOptions{})
			if err != nil || !rep.AllOK() || rep.OK != 2 {
				t.Errorf("verify: %v %s", err, rep.Text())
			}
		})
	}
}

func TestCreateOnePerFileSeveralAlgorithms(t *testing.T) {
	dir := makeTree(t, map[string]string{"a.txt": "abc", "sub/b.bin": "abc"})
	res, err := CreateChecksums(context.Background(), CreateOptions{
		Algorithms: []Algorithm{SHA256, BLAKE3},
		BaseDir:    dir,
		Paths:      []string{"a.txt", "sub"},
		OnePerFile: true,
		Format:     FormatUnix,
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Written) != 4 {
		t.Fatalf("written = %v", res.Written)
	}
	if got := readFile(t, filepath.Join(dir, "sub", "b.bin.sha256")); got != sha256abc+" *b.bin\n" {
		t.Errorf("b.bin.sha256 = %q", got)
	}
	for _, w := range res.Written {
		rep, err := VerifyChecksumFile(context.Background(), w, VerifyOptions{})
		if err != nil || !rep.AllOK() {
			t.Errorf("%s: %v %s", w, err, rep.Text())
		}
	}
	// A second run without Overwrite refuses before touching anything.
	_, err = CreateChecksums(context.Background(), CreateOptions{
		Algorithms: []Algorithm{SHA256}, BaseDir: dir, Paths: []string{"a.txt"}, OnePerFile: true,
	})
	if !errors.Is(err, os.ErrExist) {
		t.Errorf("second run error = %v, want exists", err)
	}
	_, err = CreateChecksums(context.Background(), CreateOptions{
		Algorithms: []Algorithm{SHA256}, BaseDir: dir, Paths: []string{"a.txt"}, OnePerFile: true, Overwrite: true,
	})
	if err != nil {
		t.Errorf("overwrite run: %v", err)
	}
}

func TestCreateDefaultNameAndSkipsOwnOutput(t *testing.T) {
	dir := makeTree(t, map[string]string{"proj/a.txt": "abc", "proj/b.txt": "abc"})
	base := filepath.Join(dir, "proj")
	// Selecting "." (the whole folder) names the file after the folder and
	// must not list the checksum file being written.
	_, err := CreateChecksums(context.Background(), CreateOptions{
		Algorithms: []Algorithm{MD5}, BaseDir: base, Paths: []string{"a.txt", "b.txt"}, Format: FormatUnix,
	})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(base, "proj.md5")); err != nil {
		t.Fatalf("default name: %v", err)
	}
	_, err = CreateChecksums(context.Background(), CreateOptions{
		Algorithms: []Algorithm{SHA1}, BaseDir: base, Paths: []string{"."}, OutputName: "self", Format: FormatUnix,
	})
	if err != nil {
		t.Fatal(err)
	}
	got := readFile(t, filepath.Join(base, "self.sha"))
	if strings.Contains(got, "self.sha") || !strings.Contains(got, "proj.md5") {
		t.Errorf("self.sha = %q", got)
	}
	// Single file selection names the output after that file.
	_, err = CreateChecksums(context.Background(), CreateOptions{
		Algorithms: []Algorithm{CRC32}, BaseDir: base, Paths: []string{"a.txt"},
	})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(base, "a.txt.sfv")); err != nil {
		t.Errorf("single selection name: %v", err)
	}
	// The common file is not replaced without Overwrite.
	_, err = CreateChecksums(context.Background(), CreateOptions{
		Algorithms: []Algorithm{CRC32}, BaseDir: base, Paths: []string{"a.txt"},
	})
	if !errors.Is(err, os.ErrExist) {
		t.Errorf("expected exists error, got %v", err)
	}
}

