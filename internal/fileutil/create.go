// Creating checksum files is TC's cm_CRCCreate ("Create checksum files
// (CRC32, MD5, SHA1...)"). The user selects files and folders, picks one or
// more algorithms and chooses between one common checksum file for the whole
// selection or a separate one next to every file. Folders are walked
// recursively and their files are listed with paths relative to the panel's
// folder, so the checksum file can later be verified from the same place or
// copied along with the files. Each file is read only once even when several
// algorithms are chosen. A file that cannot be read is reported and skipped
// rather than aborting a long run, and checksum files written by this very
// run are never hashed into themselves.

package fileutil

import (
	"context"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

// LineFormat chooses line endings and path separators of a checksum file.
type LineFormat int

const (
	// FormatDefault is Unix on macOS/Linux and Windows on Windows.
	FormatDefault LineFormat = iota
	// FormatUnix uses LF and forward slashes (TC's "Unix format" option).
	FormatUnix
	// FormatWindows uses CRLF and backslashes, as TC on Windows writes.
	FormatWindows
)

func (f LineFormat) unix() bool {
	switch f {
	case FormatUnix:
		return true
	case FormatWindows:
		return false
	}
	return defaultUnixFormat
}

func newlineFor(unix bool) string {
	if unix {
		return "\n"
	}
	return "\r\n"
}

// CreateOptions configures CreateChecksums.
type CreateOptions struct {
	// Algorithms to compute. One checksum file is written per algorithm (per
	// file when OnePerFile is set).
	Algorithms []Algorithm
	// BaseDir is the folder names are written relative to, normally the
	// panel's current folder. It is required.
	BaseDir string
	// Paths are the selected files and folders, absolute or relative to
	// BaseDir. Folders are included recursively.
	Paths []string
	// OnePerFile writes "name.ext.md5" next to every file, containing just
	// that file's base name, instead of one common file.
	OnePerFile bool
	// OutputName is the common checksum file's name without extension. When
	// empty it is the selected item's name for a single selection, else the
	// name of BaseDir, as TC does.
	OutputName string
	// OutputDir is where the common checksum file goes (default BaseDir).
	OutputDir string
	// Format picks line endings and separators.
	Format LineFormat
	// BSDStyle writes "SHA256 (name) = digest" lines instead of the GNU
	// "digest *name" layout. CRC32 always uses the SFV layout.
	BSDStyle bool
	// Uppercase writes hex digits in upper case. SFV digests are always
	// upper case, as every SFV tool writes them.
	Uppercase bool
	// Overwrite allows replacing existing checksum files.
	Overwrite bool
	// Comment is an optional "; ..." line written at the top of SFV files
	// (for example "Generated by mormiCommander"). Other layouts get none,
	// because older md5sum versions report comment lines as errors.
	Comment  string
	Progress ProgressFunc
}

// CreateResult reports what CreateChecksums did.
type CreateResult struct {
	Written []string     // checksum files written
	Hashed  int          // number of files hashed successfully
	Bytes   int64        // bytes read
	Failed  []FileDigest // files that could not be read, with the error
}

type createItem struct {
	abs  string
	rel  string // relative to BaseDir, with OS separators
	size int64
}

// CreateChecksums hashes the selection and writes the checksum file(s).
func CreateChecksums(ctx context.Context, opts CreateOptions) (*CreateResult, error) {
	if len(opts.Algorithms) == 0 {
		return nil, errors.New("no checksum type chosen")
	}
	seen := map[Algorithm]bool{}
	for _, a := range opts.Algorithms {
		if !a.Valid() {
			return nil, fmt.Errorf("unknown checksum type %v", a)
		}
		if seen[a] {
			return nil, fmt.Errorf("checksum type %v chosen twice", a)
		}
		seen[a] = true
	}
	if opts.BaseDir == "" {
		return nil, errors.New("no base folder given")
	}
	if len(opts.Paths) == 0 {
		return nil, errors.New("no files selected")
	}
	base, err := filepath.Abs(opts.BaseDir)
	if err != nil {
		return nil, err
	}
	unix := opts.Format.unix()
	nl := newlineFor(unix)

	// Work out the common output paths first so the walk can skip them.
	outDir := opts.OutputDir
	if outDir == "" {
		outDir = base
	}
	outName := opts.OutputName
	if outName == "" {
		if len(opts.Paths) == 1 {
			outName = filepath.Base(filepath.Clean(opts.Paths[0]))
		} else {
			outName = filepath.Base(base)
		}
		if outName == "" || outName == "." || outName == string(filepath.Separator) {
			outName = "checksums"
		}
	}
	common := map[Algorithm]string{}
	skip := map[string]bool{}
	if !opts.OnePerFile {
		for _, a := range opts.Algorithms {
			p, err := filepath.Abs(filepath.Join(outDir, outName+a.Extension()))
			if err != nil {
				return nil, err
			}
			common[a] = p
			skip[p] = true
			if !opts.Overwrite {
				if _, err := os.Lstat(p); err == nil {
					return nil, &os.PathError{Op: "create", Path: p, Err: ErrExists}
				}
			}
		}
	}

	items, total, err := collectItems(base, opts.Paths, skip)
	if err != nil {
		return nil, err
	}
	if opts.OnePerFile && !opts.Overwrite {
		// Fail before any work rather than halfway through a long run.
		for _, it := range items {
			for _, a := range opts.Algorithms {
				if _, err := os.Lstat(it.abs + a.Extension()); err == nil {
					return nil, &os.PathError{Op: "create", Path: it.abs + a.Extension(), Err: ErrExists}
				}
			}
		}
	}
	t := newTracker(ctx, opts.Progress, total)
	res := &CreateResult{}
	lines := map[Algorithm]*strings.Builder{}
	for _, a := range opts.Algorithms {
		lines[a] = &strings.Builder{}
		if a == CRC32 && opts.Comment != "" && !opts.OnePerFile {
			lines[a].WriteString("; " + opts.Comment + nl)
		}
	}
	var written []string
	fail := func(err error) (*CreateResult, error) {
		if errors.Is(err, ErrCanceled) {
			removeAll(written)
			res.Written = nil
		}
		return res, err
	}

	for _, it := range items {
		if err := t.check(); err != nil {
			return fail(err)
		}
		d, err := t.hashFile(it.abs, opts.Algorithms, it.size)
		if err != nil {
			if t.check() != nil {
				return fail(t.check())
			}
			res.Failed = append(res.Failed, FileDigest{Path: it.abs, Err: err})
			continue
		}
		res.Hashed++
		res.Bytes += it.size
		for _, a := range opts.Algorithms {
			digest := d[a]
			if opts.Uppercase {
				digest = strings.ToUpper(digest)
			}
			name := it.rel
			if opts.OnePerFile {
				name = filepath.Base(it.abs)
			}
			name = toFormatSeparators(name, unix)
			line := formatFor(a, opts.BSDStyle, name, digest) + nl
			if opts.OnePerFile {
				p := it.abs + a.Extension()
				content := line
				if a == CRC32 && opts.Comment != "" {
					content = "; " + opts.Comment + nl + line
				}
				if err := writeTextFile(p, content, opts.Overwrite); err != nil {
					return fail(err)
				}
				written = append(written, p)
				res.Written = append(res.Written, p)
			} else {
				lines[a].WriteString(line)
			}
		}
	}
	if !opts.OnePerFile {
		for _, a := range opts.Algorithms {
			if err := writeTextFile(common[a], lines[a].String(), opts.Overwrite); err != nil {
				return fail(err)
			}
			written = append(written, common[a])
			res.Written = append(res.Written, common[a])
		}
	}
	return res, nil
}

func formatFor(a Algorithm, bsd bool, name, digest string) string {
	switch {
	case a == CRC32:
		return FormatLine(StyleSFV, a, name, digest, true)
	case bsd:
		return FormatLine(StyleBSD, a, name, digest, true)
	default:
		return FormatLine(StyleGNU, a, name, digest, true)
	}
}

// toFormatSeparators converts OS separators in a relative name to the ones
// the chosen format uses.
func toFormatSeparators(name string, unix bool) string {
	name = filepath.ToSlash(name)
	if !unix {
		name = strings.ReplaceAll(name, "/", `\`)
	}
	return name
}

// collectItems expands the selection into a list of regular files with names
// relative to base. Symbolic links to folders are not followed, so a link
// loop cannot make the walk run forever.
func collectItems(base string, paths []string, skip map[string]bool) ([]createItem, int64, error) {
	var items []createItem
	var total int64
	dup := map[string]bool{}
	add := func(abs string, size int64) {
		if skip[abs] || dup[abs] {
			return
		}
		dup[abs] = true
		rel, err := filepath.Rel(base, abs)
		if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
			rel = abs
		}
		items = append(items, createItem{abs: abs, rel: rel, size: size})
		total += size
	}
	for _, p := range paths {
		abs := p
		if !filepath.IsAbs(abs) {
			abs = filepath.Join(base, p)
		}
		abs = filepath.Clean(abs)
		fi, err := os.Stat(abs)
		if err != nil {
			return nil, 0, err
		}
		if !fi.IsDir() {
			add(abs, fi.Size())
			continue
		}
		err = filepath.WalkDir(abs, func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() {
				return nil
			}
			info, err := os.Stat(path) // follows links to files
			if err != nil || !info.Mode().IsRegular() {
				return nil
			}
			add(path, info.Size())
			return nil
		})
		if err != nil {
			return nil, 0, err
		}
	}
	return items, total, nil
}

// writeTextFile writes content to path, refusing to replace an existing file
// unless overwrite is set.
func writeTextFile(path, content string, overwrite bool) error {
	f, err := createOutput(path, overwrite)
	if err != nil {
		return err
	}
	if _, err := f.WriteString(content); err != nil {
		f.Close()
		os.Remove(path)
		return err
	}
	return f.Close()
}
